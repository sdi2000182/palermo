const used = {};
export function line(key, vars) {
  const opts = T[key] || [key];
  // avoid repeating the last take of the same line
  let i = Math.floor(Math.random() * opts.length);
  if (opts.length > 1 && i === used[key]) i = (i + 1) % opts.length;
  used[key] = i;
  return opts[i].replace(/\{(\w+)\}/g, (_, k) => vars && vars[k] != null ? vars[k] : '');
}
